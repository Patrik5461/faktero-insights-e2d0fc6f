-- Vozový park: údaje z technického preukazu, vlastníctvo, termíny a poistky.
-- Tá istá tabuľka ako v Knihe jázd — vozidlo je jedno, agendy dve.
alter table public.vehicles
  add column if not exists vin text,
  add column if not exists znacka text,
  add column if not exists model text,
  add column if not exists rok_vyroby integer check (rok_vyroby between 1900 and 2100),
  add column if not exists datum_prvej_evidencie date,
  add column if not exists farba text,
  add column if not exists kategoria text,
  add column if not exists objem_cm3 integer check (objem_cm3 >= 0),
  add column if not exists vykon_kw numeric(8,1) check (vykon_kw >= 0),
  add column if not exists celkova_hmotnost_kg integer check (celkova_hmotnost_kg >= 0),
  add column if not exists pocet_miest integer check (pocet_miest >= 0),
  add column if not exists vlastnictvo text check (vlastnictvo in ('vlastne','financny_leasing','operativny_leasing','uver','prenajom','sukromne')),
  add column if not exists vlastnik_nazov text,
  add column if not exists vlastnik_ico text,
  add column if not exists drzitel_nazov text,
  add column if not exists financing_contract_id uuid references public.financing_contracts(id) on delete set null,
  add column if not exists datum_obstarania date,
  add column if not exists obstaravacia_cena numeric(14,2) check (obstaravacia_cena >= 0),
  add column if not exists pouzitie text check (pouzitie in ('podnikanie','zmiesane')),
  add column if not exists odpocet_dph text check (odpocet_dph in ('100','50','0')),
  add column if not exists vodic text,
  add column if not exists stk_do date,
  add column if not exists ek_do date,
  add column if not exists pzp_poistovna text,
  add column if not exists pzp_cislo text,
  add column if not exists pzp_do date,
  add column if not exists havarijne_poistovna text,
  add column if not exists havarijne_cislo text,
  add column if not exists havarijne_do date,
  add column if not exists dialnicna_znamka_do date,
  add column if not exists servis_datum date,
  add column if not exists servis_km integer check (servis_km >= 0),
  add column if not exists dmv boolean not null default false,
  add column if not exists poznamka text,
  add column if not exists vyradene_dna date;

create index if not exists vehicles_financing_contract_idx on public.vehicles (financing_contract_id) where financing_contract_id is not null;
