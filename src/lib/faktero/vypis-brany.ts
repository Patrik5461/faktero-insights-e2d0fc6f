/*
  Výpis z platobnej brány (Stripe, PayPal, GoPay, Comgate, Barion) ako bankový
  výpis.

  Brána je pre účtovníctvo samostatný „účet": prídu na ňu platby zákazníkov,
  strhne si z nich poplatok a zvyšok raz za čas pošle na bankový účet. Účtovník
  to dovtedy prepisoval z exportu brány ručne — riadok po riadku, s poplatkom
  zvlášť. Tu sa z exportu stanú pohyby v tvare, aký majú bankové výpisy, a
  ďalej idú tou istou cestou: do Pohody (dávka alebo camt.053), do Faktera na
  párovanie s faktúrami.

  Každý riadok brány dá:
    - platbu (príjem, označenie „Úhrada faktúry"),
    - poplatok ako samostatný výdaj („Bankový poplatok"),
    - a výber na bankový účet ako výdaj („Prevod medzi vlastnými účtami").

  Formáty sa poznávajú podľa hlavičky. Názvy stĺpcov sú podľa dokumentácie
  brán; PayPal a GoPay ich prekladajú do jazyka účtu, preto sa porovnávajú
  bez diakritiky a s viacerými názvami naraz.
*/
import { citajCsv, cisloZTextu, normalizuj } from "./import-prijatych";
import type { VypisPohyb } from "./export.server";
import type { Vypis } from "./vypis-pohyby";

export type Brana = "stripe" | "paypal" | "gopay" | "comgate" | "barion" | "iny";

export const NAZVY_BRAN: Record<Brana, string> = {
  stripe: "Stripe",
  paypal: "PayPal",
  gopay: "GoPay",
  comgate: "Comgate",
  barion: "Barion",
  iny: "Platobná brána",
};

/** Pohyb s identifikátorom z brány — podľa neho sa pri opakovanom nahraní nič nezdvojí. */
export type PohybBrany = VypisPohyb & { id: string };

export type VypisBrany = Omit<Vypis, "pohyby"> & {
  brana: Brana;
  pohyby: PohybBrany[];
  pocty: { platby: number; poplatky: number; vybery: number; vratenia: number };
  varovanie: string | null;
};

type Pole =
  | "id"
  | "datum"
  | "cas"
  | "brutto"
  | "poplatok"
  | "netto"
  | "suma"
  | "mena"
  | "typ"
  | "stav"
  | "meno"
  | "email"
  | "referencia"
  | "referencia2"
  | "popis"
  | "zostatok"
  | "datumPrevodu"
  | "prevedene"
  | "vsPrevodu";

type Stlpce = Partial<Record<Pole, number>>;

/** Hlavička na porovnanie: malé písmená, bez diakritiky, len písmená a číslice. */
export function holaHlavicka(v: unknown): string {
  return normalizuj(v)
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

